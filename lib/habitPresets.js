export function getLocalizedPreset(preset, lang = 'ar') {
  const isAr = lang === 'ar';
  return {
    id: preset.id,
    name: isAr ? preset.titleAr : preset.titleEn,
    subtitle: isAr ? preset.subtitleAr : preset.subtitleEn,
    badgeText: isAr ? preset.badgeTextAr : preset.badgeTextEn,
    type: preset.type,
    subItems: isAr ? [...preset.subItemsAr] : [...preset.subItemsEn],
    frequency: preset.frequency,
    scheduleDays: preset.scheduleDays || [0, 1, 2, 3, 4, 5, 6],
    time: preset.time,
    duration: preset.duration,
    location: preset.location,
    category: preset.category || 'habit',
  };
}
